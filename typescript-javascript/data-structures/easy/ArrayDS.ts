/**
 * Reverses the elements of an array.
 * 
 * @param {number[]} a - The input array to be reversed.
 * 
 * @returns {number[]} The reversed array.
 */
function reverseArray(a: number[]): number[]
{
    return(a.reverse());
}//end reverseArray()